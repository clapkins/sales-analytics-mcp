"""Точка входа MCP-сервера через транспорт stdio.

На этапе 0 сервер содержит только диагностический инструмент ``ping`` —
он нужен исключительно чтобы убедиться, что клиент (Claude Desktop)
подхватывает сервер и может вызывать инструменты. Начиная с этапа 5
инструменты будут генерироваться из реестра скиллов (``core/registry``),
а не объявляться здесь вручную.
"""

from fastmcp import FastMCP

mcp = FastMCP("sales-analytics")


@mcp.tool
def ping() -> str:
    """Проверяет, что сервер запущен и доступен клиенту.

    Returns:
        Строка-подтверждение того, что сервер отвечает на вызовы.
    """
    return "pong"


if __name__ == "__main__":
    mcp.run()
